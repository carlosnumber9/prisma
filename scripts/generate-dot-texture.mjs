import { writeFileSync } from 'node:fs';

const size = 1440;
const spacing = 20;
const maximumRadius = 2.15;
const circles = [];

function gaussian(distance, width) {
  return Math.exp(-((distance / width) ** 2));
}

for (let y = spacing / 2; y < size; y += spacing) {
  // Whole periods make the vertical repeat continuous, including its slope.
  const phase = (y / size) * Math.PI * 2;
  for (let x = spacing / 2; x < size; x += spacing) {
    const leftFold =
      gaussian(x - (290 + 240 * Math.sin(phase - 0.6)), 200) *
      (0.5 + 0.5 * Math.cos(phase + 0.4));
    const rightFold =
      gaussian(x - (1130 + 240 * Math.sin(phase + 1.1)), 230) *
      (0.5 + 0.5 * Math.sin(phase - 0.5));
    const lowerFold =
      gaussian(x - (710 + 310 * Math.cos(phase + 0.8)), 220) *
      (0.5 + 0.5 * Math.cos(phase - 3.7)) ** 3;
    const readingSpace = 1 - 0.65 * gaussian(x - size / 2, 240);
    const intensity = Math.min(1, leftFold + rightFold + lowerFold);
    const radius = maximumRadius * intensity ** 1.4 * readingSpace;
    if (radius < 0.12) continue;
    circles.push(`<circle cx="${x}" cy="${y}" r="${radius.toFixed(2)}"/>`);
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
<!-- Generated by scripts/generate-dot-texture.mjs. -->
<g fill="#64717b">${circles.join('')}</g>
</svg>
`;

writeFileSync(new URL('../public/dot-texture.svg', import.meta.url), svg);
console.log(`Generated dot texture with ${circles.length} circles.`);
